; T0223: the shopkeeper -> bean -> plant -> water -> BEANSTALK chain, TAPE build
; only. Assembled into TAPE_LOW_REGION3 (room36.asm, the unused tail of title
; hole 1: persistent, below $4000), between tape_low3_slot_start/_end.
;
; RULES for code in this region (it is assembled in two places: at its real
; address in the final pass and parked at $c400 in the raw measurement pass):
;   * branches INSIDE this file may be short; every reference to anything
;     outside it uses jsr/jmp/lbra/lbsr (the raw pass puts it 30 KB away);
;   * nothing here may be data the resident code reads at a fixed address.
;
; X-ALL.TXT (cited by line):
;   shopkeeperrou 3012: only in room 22, shopkeepercount (255 at start,
;     resetmoving 1827) counts down per pass; at 0 both shopkeeper records
;     get room 22 and shopkeeperappearsmess shows. update_shop.
;   proxshopkeeper 3028/proxshopkeeperrou 3031 (called for ANY dropped object,
;     5853): box (66,160,8,16) -> port (136,160,32,16) [(x-32)*4, w*4]. Only
;     once he has appeared. Cow (frame 7): cow room=255, `shoptalk` 577 pokes
;     beanhere+room = roomno (the bean appears in the room you trade in) and
;     the 8-box bargaining stream plays. Anything else: givingjunkmess, with
;     stopgivingjunkmess on every 4th (delaycounter+1 & 3 == 0). cdt_shop.
;   proxbean 3003: bean dropped in room 58 box (71,160,8,16) -> (156,160,32,16):
;     bean room=255, plantbeanmess. NOTE the original keeps NO planted state:
;     `proxfullbucketrou` works whether or not a bean was planted.
;   proxfullbucket 2990: full bucket dropped in the same box: bucket room=255,
;     x -= 10 (4px units -> 40 px), manurehere+var1 = 2 (stalk_grown here),
;     throwwateronbeanmess. checkbeanstalk 5478 then draws room 1 over room
;     58 (drawfullroom, 12 placements = stalk_places below, same sprites and
;     frame-table indices as room 74) every time room 58 is drawn.
;     tape_room_hook appends those placements to the room's list at load, so
;     the draw order, the solid/decorative flags and derive_room_cmask's
;     collision mask all come from the existing machinery.

SHOP_X          equ 136
SHOP_Y          equ 160
SHOP_W          equ 32
SHOP_H          equ 16
BEAN_X          equ 156
BEAN_Y          equ 160
BEAN_W          equ 32
BEAN_H          equ 16
SHOVE_PX        equ 40               ; `sub 10` on Dizzy's x in 4-px units
STALK_N         equ 12

TB_SHOP1        equ actor_init_tape+1*ACTOR_STRIDE   ; shopkeeperhere (frame 105)
TB_SHOP2        equ actor_init_tape+2*ACTOR_STRIDE   ; shopkeeperhere1 (mirrored half)
TB_BEAN         equ actor_init_tape+3*ACTOR_STRIDE   ; beanhere (frame 2)

; state (reset by bean_reset, called from tape_state_reset)
shop_count      fcb 255              ; shopkeepercount
shop_junk       fcb 0                ; shopkeeperhere+delaycounter
stalk_grown     fcb 0                ; manurehere+var1 == 2

; room 1's 12 placements (extracted/rooms.json room 1; frames 224-227),
; written with room 74's own frame-table indices (83=224, 84=225, 85=227,
; 86=226), which are the same sprites. x byte = x | solid(2) | mirror(1).
stalk_places
        fcb 83,162,144
        fcb 83,163,112
        fcb 83,162,80
        fcb 83,163,48
        fcb 85,186,112
        fcb 84,186,63
        fcb 86,147,144
        fcb 84,147,87
        fcb 85,155,47
        fcb 86,184,80
        fcb 84,184,145
        fcb 84,145,116

bean_reset
        clr stalk_grown
        clr shop_junk
        lda #255
        sta shop_count
        lbra ti_reset                ; T0226: the full bucket is not in the world (tape_item_code.asm)

; draw_actors' da_needs_clear: Y = a static (ROU_CROWBAR) actor; colour bit 7
; = mirrored (the shopkeeper's second half). blit_mirror is the blitter's
; one-shot parameter.
tape_static_mirror
        lda 7,y
        rola
        lda #0
        rola
        sta blit_mirror
        rts

; load_room (TAPE, packed path): the room's placements were just unpacked to
; ROOM_UNPACK_BUF. Room 58 with the stalk grown gets room 1's placements
; appended (source order = drawn/masked last, exactly like the original's
; second drawfullroom). Room 58 has no flames/water, so nothing follows the
; placements in the buffer.
tape_room_hook
        lda cur_room
        cmpa #58
        bne trh_ret
        tst stalk_grown
        beq trh_ret
        ldb room_place_count
        lda #3
        mul
        addd #ROOM_UNPACK_BUF
        tfr d,y
        ldx #stalk_places
        ldb #STALK_N*3
trh_cp
        lda ,x+
        sta ,y+
        decb
        bne trh_cp
        lda room_place_count
        adda #STALK_N
        sta room_place_count
trh_ret
        rts

; the four small messages (generated by tools/dte from text_src_tape/msg_data_tape_low3.asm)
        include "msg_data_tape_low3.asm"

; shopkeeperrou, chained from update_dozy's exit (every pass).
update_shop
        lda cur_room
        cmpa #22
        bne us_ret
        lda shop_count
        beq us_ret
        deca
        sta shop_count
        bne us_ret
        lda #22
        sta TB_SHOP1
        sta TB_SHOP2
        jsr msg_begin
        ldx #msg_shopappears
        jmp msg_box_done             ; ... which repaints both buffers
us_ret
        rts

; check_drop_trigger (TAPE) for ANY dropped item, X = its record; X is
; preserved for the frame dispatch that follows.
cdt_shop
        pshs x
        bsr cs_body
        puls x
        rts
cs_body
        lda cur_room
        cmpa #22
        bne cs_ret
        tst shop_count
        bne cs_ret                   ; he has not appeared yet
        lda #SHOP_X
        sta ah_bx
        lda #SHOP_Y
        sta ah_by
        lda #SHOP_W
        sta ah_bw
        lda #SHOP_H
        pshs x
        jsr aabb_test
        puls x
        beq cs_ret
        lda 4,x
        cmpa #FRAME_COW
        bne cs_junk
        lda #255
        sta ,x                       ; the cow is consumed
        lda cur_room
        sta TB_BEAN                  ; shoptalk's `defw beanhere+room`
        ldx #msg_shoptalk
        jsr msg_chatter
        jmp force_redraw
cs_junk
        jsr msg_begin
        lda shop_junk
        inca
        anda #3
        sta shop_junk
        bne cs_giving
        ldx #msg_stopjunk
        bra cs_say
cs_giving
        ldx #msg_givingjunk
cs_say
        jmp msg_box_done
cs_ret
        rts

; check_drop_trigger's tail (TAPE): the rope test failed. A = frame, X = item.
; Egg (T0239) and rocks (T0216) used to be tested inline there.
cdt_tape
        cmpa #10
        lbeq cdt_egg
        cmpa #136
        lbhs cdt_rock
        cmpa #FRAME_BEAN
        beq ct_bean
        cmpa #FRAME_BUCKET
        lbeq cdt_bucket              ; T0226 (tape_item_code.asm): empty vs full bucket
        cmpa #FRAME_KNOCKER
        lbeq cdt_knocker
        cmpa #FRAME_PICKAXE
        lbeq cdt_pickaxe
        cmpa #FRAME_RUG
        lbeq cdt_rug                 ; T0227 (tape_item_code.asm)
        rts
ct_water
        ; ---- proxfullbucket: water the bean (the FULL bucket only, cdt_bucket)
        bsr ct_box58
        beq ct_done
        lda #255
        sta ,x                       ; the bucket is consumed
        lda dizzy_x
        suba #SHOVE_PX
        bhs ct_shove
        clra
ct_shove
        sta dizzy_x
        lda #1
        sta stalk_grown
        jsr msg_begin
        ldx #msg_waterbean
        jsr msg_box_done
        jsr load_room                ; rebuild room 58's placements + mask with the stalk
        jmp force_redraw
ct_bean
        ; ---- proxbean: plant it ("unable to grow")
        bsr ct_box58
        beq ct_done
        lda #255
        sta ,x                       ; the bean is consumed
        jsr msg_begin
        ldx #msg_plantbean
        jmp msg_box_done
ct_done
        rts

; Z set = not in room 58's bean box. X preserved.
ct_box58
        lda cur_room
        cmpa #58
        bne ct_no
        lda #BEAN_X
        sta ah_bx
        lda #BEAN_Y
        sta ah_by
        lda #BEAN_W
        sta ah_bw
        lda #BEAN_H
        pshs x
        jsr aabb_test
        puls x
        rts
ct_no
        clra
        rts
