#!/usr/bin/env bash
# Remove exactly the files tools/bootstrap.sh regenerates (docs/PROVENANCE.md, "What the bootstrap
# generates"). Dry run by default: lists what WOULD go. Pass --yes to delete.
#
# Never touched: hand-authored sources (target/room36.asm, title_mix3.asm, win_mix3.asm, the other
# hand-written .asm, target/text_tpl*, target/*.asm that are not in the lists below), tools/, harness/,
# docs/, NOTES.md, the user-supplied inputs (research/D3-prior-art/{original_source,info}, source/),
# built tool binaries (tools/*/target) and preview PNGs.
#
# None of these are tracked in git (they are all gitignored); deleting them proves the bootstrap
# rebuilds them. extracted/game_text.json is removed too: it is your text, regenerated by `extract`.
#
# Usage: tools/clean_generated.sh [--yes]
set -euo pipefail
cd "$(dirname "$0")/.."

YES=0
for a in "$@"; do
    case "$a" in
        --yes) YES=1 ;;
        -h|--help) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "clean_generated.sh: unknown argument '$a' (only --yes)" >&2; exit 2 ;;
    esac
done

shopt -s nullglob
# Globs, relative to the port root. Keep in step with docs/PROVENANCE.md.
PATTERNS=(
    # extract
    extracted/rooms.json extracted/actors.json extracted/frmtable.json extracted/game_text.json
    # frame-split (dizzy-pack-all output + the split)
    target/dizzy_frames_all.asm target/dizzy_frames_bodyA.asm target/dizzy_frames_bodyB.asm target/dizzy_frames_tail.asm
    # mksounds.sh
    target/sound_data.asm
    tools/aycapture/captures/beep_tune0.csv tools/aycapture/captures/mix3_stream.asm
    tools/aycapture/captures/tune0.csv tools/aycapture/captures/tune0_title.asm
    tools/aycapture/captures/tune1.csv tools/aycapture/captures/tune1.asm
    tools/aycapture/captures/tune2.csv tools/aycapture/captures/tune2.asm
    tools/aycapture/captures/tune3_win.csv
    tools/aycapture/captures/tune5.csv tools/aycapture/captures/tune5.asm
    'tools/aycapture/captures/fx1.*' 'tools/aycapture/captures/fx6.*' 'tools/aycapture/captures/fx10.*'
    'tools/aycapture/captures/fx11.*' 'tools/aycapture/captures/fx21.*' 'tools/aycapture/captures/fx25.*'
    # regen_art.sh (roompack)
    'target/room[0-9]*_data*.asm' target/font_data.asm 'target/frame_table_data*.asm'
    'target/actor_data*.asm' 'target/coin_data*.asm' 'target/shared_*_data.asm'
    # textsplit fill (target/text_tpl* + game_text.json) and dte build (from target/text_src*)
    target/text_src target/text_src_tape
    # textsplit export-lua (harness fixture: the original's strings keyed X-ALL:<line>)
    harness/orig_text.lua
    target/gameplay.asm target/gap_messages.asm target/actors.asm target/ui_room_names.asm
    target/rat_troll_hazard_code.asm target/dte_table.asm 'target/msg_data_*.asm'
    # stage_pack.sh
    'target/staged_*_lz*.asm' 'target/staged_syms*.asm' 'target/staged_[cd]_raw*.bin' 'target/image_end_lz*.asm'
    'target/title_frags*.asm' 'target/title_lz*.asm' 'target/title_resident_*.asm'
    'target/win_mix3_lz*.asm' 'target/win_mix3_syms*.asm'
    # final artifacts and their maps
    target/room36.bin target/room36_tape.bin target/room36_floppy.bin
    target/room36.map target/room36_tape.map target/room36_floppy.map
    target/room36.cas target/dizzy.dsk
    target/floppy
    # bootstrap's own logs
    target/bootstrap_logs
)
# Safety net: whatever a glob above matches, these hand-authored files are never removed.
PROTECT=(target/room36.asm target/room36_cart.asm target/title_mix3.asm target/win_mix3.asm target/text_tpl target/text_tpl_tape)

declare -a HIT=()
for pat in "${PATTERNS[@]}"; do
    # shellcheck disable=SC2206
    for f in $pat; do
        skip=0
        for p in "${PROTECT[@]}"; do [ "$f" = "$p" ] && skip=1; done
        [ $skip = 1 ] || HIT+=("$f")
    done
done

if [ ${#HIT[@]} -eq 0 ]; then echo "clean_generated.sh: nothing to remove"; exit 0; fi
if [ $YES = 0 ]; then
    printf '%s\n' "${HIT[@]}"
    echo "clean_generated.sh: ${#HIT[@]} generated path(s) would be removed (dry run; pass --yes)" >&2
    exit 0
fi
rm -rf -- "${HIT[@]}"
echo "clean_generated.sh: removed ${#HIT[@]} generated path(s)"
