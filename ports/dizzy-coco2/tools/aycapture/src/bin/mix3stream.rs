//! Build a THREE-VOICE event stream from an aycapture CSV, for the
//! standalone mixer prototype harness/mixer3.asm.
//!
//! WHY: the shipping title tune is the AY melody alone (one blocking DAC
//! voice) and the open question for the user is whether bringing back the
//! bass and harmony is worth its cost. This lets that be HEARD on the real
//! target DAC before any memory-map work: the prototype runs standalone,
//! outside the game.
//!
//! STREAM FORMAT (read by mixer3.asm's `event`):
//!   [delay][mask][data...]  repeated, a delay of 0 ends (and loops) it
//!   delay = 50Hz ticks until the NEXT record (1..255; longer gaps are
//!           split with empty records, mask 0)
//!   mask  = bit5/4/3: new phase increment for A/B/C (2 bytes each, big
//!           endian, in that order); bit2/1/0: new amplitude for A/B/C
//!           (1 byte each, in that order)
//! A phase increment is f * 65536 / sample_rate; the voice is the top bit
//! of its 16-bit accumulator. Amplitudes are DAC values in steps of 4 (the
//! DAC is bits 7-2), at most 84 so three voices sum to 252.
//!
//! Usage:
//!   mix3stream <capture.csv> <total_frames> <sample_rate> <out.asm> [--semitone]
//!   mix3stream - 0 <sample_rate> <out.asm> --cal <hz>     (one steady tone, for calibration)
use std::env;
use std::fs;

const AY_LEVEL: [f64; 16] = [
    0.0, 0.0128, 0.0185, 0.0271, 0.0400, 0.0591, 0.0824, 0.1346, 0.1586, 0.2549, 0.3561,
    0.4470, 0.5641, 0.7083, 0.8422, 1.0,
];

fn main() {
    let a: Vec<String> = env::args().collect();
    if a.len() < 5 {
        eprintln!("usage: mix3stream <capture.csv> <total_frames> <sample_rate> <out.asm> [--semitone | --cal HZ]");
        std::process::exit(2);
    }
    let sr: f64 = a[3].parse().expect("sample_rate");
    let out = &a[4];
    let semitone = a.iter().any(|x| x == "--semitone");
    let cal: Option<f64> = a
        .iter()
        .position(|x| x == "--cal")
        .map(|i| a[i + 1].parse().expect("--cal HZ"));

    let mut s = String::from("; AUTO-GENERATED by tools/aycapture/mix3stream -- DO NOT EDIT.\nstream\n");

    if let Some(hz) = cal {
        let inc = (hz * 65536.0 / sr).round() as u32;
        s.push_str(&format!(
            "\tfcb 255,$24,${:02x},${:02x},84\n\tfcb 0\n",
            inc >> 8,
            inc & 255
        ));
        fs::write(out, s).expect("write");
        println!("calibration stream: {hz}Hz at assumed SR {sr} -> inc {inc}");
        return;
    }

    let csv = fs::read_to_string(&a[1]).expect("read csv");
    let total: u32 = a[2].parse().expect("total_frames");
    let rows: Vec<(u32, [u32; 14])> = csv
        .lines()
        .skip(1)
        .filter(|l| !l.is_empty())
        .map(|l| {
            let v: Vec<u32> = l.split(',').map(|x| x.parse().unwrap()).collect();
            let mut r = [0u32; 14];
            r.copy_from_slice(&v[1..15]);
            (v[0], r)
        })
        .collect();

    // Per-frame voice state. The capture only logs frames where a register
    // changed, so the register state is held between rows.
    let mut state = [0u32; 14];
    let mut ri = 0;
    let mut prev = [(0u16, 0u8); 3];
    let mut events: Vec<(u32, u8, Vec<u8>)> = Vec::new();
    for fr in 0..total {
        while ri < rows.len() && rows[ri].0 <= fr {
            state = rows[ri].1;
            ri += 1;
        }
        let mut cur = prev;
        for ch in 0..3 {
            let (lo, hi, vr) = [(0, 1, 8), (2, 3, 9), (4, 5, 10)][ch];
            let period = state[lo] + state[hi] * 256;
            let vol = (state[vr] & 15) as usize;
            let tone_on = (state[7] >> ch) & 1 == 0;
            if period > 0 && vol > 0 && tone_on {
                let mut f = 1_773_400.0 / (16.0 * period as f64);
                if semitone {
                    let n = (12.0 * (f / 440.0).log2()).round();
                    f = 440.0 * 2f64.powf(n / 12.0);
                }
                // keep below Nyquist: an increment of 32768 is sr/2
                let inc = ((f * 65536.0 / sr).round() as u32).min(32767) as u16;
                let amp = ((21.0 * AY_LEVEL[vol]).round() as u8) * 4;
                cur[ch] = (inc, amp);
            } else {
                // silent: amplitude 0, increment left alone (no event for it)
                cur[ch] = (prev[ch].0, 0);
            }
        }
        let mut mask = 0u8;
        let mut data = Vec::new();
        for ch in 0..3 {
            if fr == 0 || cur[ch].0 != prev[ch].0 {
                mask |= 0x20 >> ch;
                data.push((cur[ch].0 >> 8) as u8);
                data.push((cur[ch].0 & 255) as u8);
            }
        }
        for ch in 0..3 {
            if fr == 0 || cur[ch].1 != prev[ch].1 {
                mask |= 0x04 >> ch;
                data.push(cur[ch].1);
            }
        }
        if mask != 0 {
            events.push((fr, mask, data));
        }
        prev = cur;
    }

    let mut bytes = 0usize;
    for (i, (fr, mask, data)) in events.iter().enumerate() {
        let next = events.get(i + 1).map(|e| e.0).unwrap_or(total);
        let mut delay = (next - fr).max(1);
        let first = delay.min(255);
        let mut line = format!("\tfcb {},${:02x}", first, mask);
        for b in data {
            line.push_str(&format!(",${b:02x}"));
        }
        s.push_str(&line);
        s.push('\n');
        bytes += 2 + data.len();
        delay -= first;
        while delay > 0 {
            let chunk = delay.min(255);
            s.push_str(&format!("\tfcb {chunk},$00\n"));
            bytes += 2;
            delay -= chunk;
        }
    }
    s.push_str("\tfcb 0\n");
    bytes += 1;
    fs::write(out, s).expect("write");
    println!(
        "{} frames -> {} events, {} bytes ({}), SR {}",
        total,
        events.len(),
        bytes,
        if semitone { "semitone-quantised" } else { "exact periods" },
        sr
    );
}
