//! floppypack -- T0241: turn the game's DECB image into the floppy boot data.
//!
//!   floppypack --decb IN.bin --dat OUT.dat --segs OUT.asm \
//!              --loader-org 0x7600 --loader-end 0x77c0 [--page-limit 0xff00]
//!
//! DIZZY.DAT = every DECB block, sorted by ascending destination, each starting on a sector
//! boundary and zero-padded to whole sectors (the padding spills past the block's end when
//! loaded; see target/floppy_stage1.asm).  OUT.asm = the loader's table (`fdb dest / fcb sectors`,
//! `fdb 0`) plus GAME_EXEC.  HARD GUARDS (exit 1): blocks overlap; a block's padded end reaches
//! the loader window, the I/O page, or any block that is loaded EARLIER (= has a lower address,
//! so a spill into it would corrupt it -- spill may only land on later blocks or on unloaded RAM).
use std::process::exit;

fn die(m: &str) -> ! {
    eprintln!("floppypack: {m}");
    exit(1)
}

fn num(s: &str) -> usize {
    let t = s.trim_start_matches('$').trim_start_matches("0x");
    usize::from_str_radix(t, 16).unwrap_or_else(|_| die(&format!("bad hex {s}")))
}

/// DECB image -> (blocks, exec)
pub fn parse_decb(d: &[u8]) -> Result<(Vec<(usize, Vec<u8>)>, usize), String> {
    let (mut pos, mut v) = (0usize, vec![]);
    while pos < d.len() {
        match d[pos] {
            0 => {
                if pos + 5 > d.len() { return Err("truncated block header".into()); }
                let ln = (d[pos + 1] as usize) << 8 | d[pos + 2] as usize;
                let ad = (d[pos + 3] as usize) << 8 | d[pos + 4] as usize;
                if pos + 5 + ln > d.len() { return Err("truncated block".into()); }
                v.push((ad, d[pos + 5..pos + 5 + ln].to_vec()));
                pos += 5 + ln;
            }
            0xFF => {
                if pos + 5 > d.len() { return Err("truncated trailer".into()); }
                return Ok((v, (d[pos + 3] as usize) << 8 | d[pos + 4] as usize));
            }
            t => return Err(format!("unknown DECB block type {t:#x}")),
        }
    }
    Err("no trailer".into())
}

pub struct Packed {
    pub dat: Vec<u8>,
    pub asm: String,
    pub sectors: usize,
}

pub fn pack(blocks: &[(usize, Vec<u8>)], exec: usize, loader: (usize, usize), limit: usize) -> Result<Packed, String> {
    let mut b: Vec<(usize, Vec<u8>)> = blocks.iter().filter(|(_, d)| !d.is_empty()).cloned().collect();
    b.sort_by_key(|(a, _)| *a);
    // blocks that touch (end == next start) are one segment: no padding between them, one read
    let mut m: Vec<(usize, Vec<u8>)> = vec![];
    for (a, d) in b {
        match m.last_mut() {
            Some((la, ld)) if *la + ld.len() == a => ld.extend_from_slice(&d),
            _ => m.push((a, d)),
        }
    }
    let b = m;
    let mut errs = vec![];
    for (i, (a, d)) in b.iter().enumerate() {
        let end = a + d.len();
        let pend = a + d.len().div_ceil(256) * 256;
        if end > limit { errs.push(format!("block ${a:04x}-${end:04x} reaches ${limit:04x}")); }
        if pend > limit { errs.push(format!("block ${a:04x}: padded end ${pend:04x} reaches the I/O page ${limit:04x}")); }
        if *a < loader.1 && loader.0 < pend {
            errs.push(format!("block ${a:04x}-${end:04x} (padded to ${pend:04x}) overlaps the loader ${:04x}-${:04x}", loader.0, loader.1));
        }
        if i + 1 < b.len() && end > b[i + 1].0 {
            errs.push(format!("block ${a:04x}-${end:04x} overlaps the next block at ${:04x}", b[i + 1].0));
        }
    }
    if !errs.is_empty() { return Err(errs.join("\n  ")); }
    let mut dat = vec![];
    let mut asm = String::from("; Generated by tools/dskwriter floppypack (tools/floppy_pack.sh) -- do not edit.\n; seg_table: destination, whole sectors read from DIZZY.DAT in order.\nseg_table\n");
    let mut sectors = 0;
    for (a, d) in &b {
        let s = d.len().div_ceil(256);
        asm += &format!("        fdb ${a:04x}\n        fcb {s}            ; {} bytes, ends ${:04x}\n", d.len(), a + d.len());
        dat.extend_from_slice(d);
        dat.resize(dat.len().div_ceil(256) * 256, 0);
        sectors += s;
    }
    // The driver's NMI hook is a JMP written over $0109-$010B (BASIC's RAM NMI vector) on every
    // call; the loader does not restore it (no room), so it re-stores the image's own bytes there
    // at the end.  If no block covers those three bytes the values are irrelevant (0).
    let mut nmi = [0u8; 3];
    for (a, d) in &b {
        for (k, slot) in nmi.iter_mut().enumerate() {
            let at = 0x109 + k;
            if *a <= at && at < a + d.len() {
                *slot = d[at - a];
            }
        }
    }
    asm += &format!("        fdb 0\nGAME_EXEC equ ${exec:04x}\nDAT_SECTORS equ {sectors}\nGAME_NMI0 equ ${:02x}\nGAME_NMI12 equ ${:02x}{:02x}\n", nmi[0], nmi[1], nmi[2]);
    Ok(Packed { dat, asm, sectors })
}

fn main() {
    let a: Vec<String> = std::env::args().skip(1).collect();
    let get = |k: &str| a.iter().position(|x| x == k).and_then(|i| a.get(i + 1)).cloned();
    let decb = get("--decb").unwrap_or_else(|| die("--decb"));
    let (blocks, exec) = parse_decb(&std::fs::read(&decb).unwrap_or_else(|e| die(&format!("{decb}: {e}")))).unwrap_or_else(|e| die(&e));
    let lo = num(&get("--loader-org").unwrap_or_else(|| die("--loader-org")));
    let hi = num(&get("--loader-end").unwrap_or_else(|| die("--loader-end")));
    let lim = get("--page-limit").map(|s| num(&s)).unwrap_or(0xFF00);
    let p = pack(&blocks, exec, (lo, hi), lim).unwrap_or_else(|e| die(&format!("GUARD FAILED:\n  {e}")));
    std::fs::write(get("--dat").unwrap_or_else(|| die("--dat")), &p.dat).unwrap_or_else(|e| die(&e.to_string()));
    std::fs::write(get("--segs").unwrap_or_else(|| die("--segs")), &p.asm).unwrap_or_else(|e| die(&e.to_string()));
    println!("floppypack: {} blocks, {} sectors ({} bytes) in DIZZY.DAT, exec ${exec:04x}", blocks.len(), p.sectors, p.dat.len());
}

#[cfg(test)]
mod tests {
    use super::*;

    fn decb(blocks: &[(usize, Vec<u8>)], exec: usize) -> Vec<u8> {
        let mut v = vec![];
        for (a, d) in blocks {
            v.extend_from_slice(&[0, (d.len() >> 8) as u8, d.len() as u8, (*a >> 8) as u8, *a as u8]);
            v.extend_from_slice(d);
        }
        v.extend_from_slice(&[0xFF, 0, 0, (exec >> 8) as u8, exec as u8]);
        v
    }

    #[test]
    fn parse_and_pack_round_trip() {
        let blocks = vec![(0x8000, vec![7u8; 300]), (0x2000, vec![1u8; 256]), (0x4000, vec![3u8; 5])];
        let (p, e) = parse_decb(&decb(&blocks, 0x4000)).unwrap();
        assert_eq!((p.len(), e), (3, 0x4000));
        let k = pack(&p, e, (0x7600, 0x77c0), 0xFF00).unwrap();
        // ascending: 0x2000 (1 sector), 0x4000 (1), 0x8000 (2)
        assert_eq!(k.sectors, 4);
        assert_eq!(k.dat.len(), 4 * 256);
        assert!(k.dat[..256].iter().all(|&b| b == 1));
        assert_eq!(k.dat[256], 3);
        assert_eq!(k.dat[257 + 4], 0);
        assert_eq!(k.dat[512 + 299], 7);
        assert_eq!(k.dat[512 + 300], 0);
        assert!(k.asm.contains("fdb $2000") && k.asm.contains("GAME_EXEC equ $4000"));
    }

    #[test]
    fn touching_blocks_merge_into_one_segment() {
        let k = pack(&[(0x2000, vec![1; 100]), (0x2064, vec![2; 200]), (0x2200, vec![3; 10])], 0x2000, (0x7600, 0x77c0), 0xFF00).unwrap();
        // 0x2000+100 == 0x2064 -> merged (300 bytes = 2 sectors); 0x2200 is separate (1 sector)
        assert_eq!(k.sectors, 3);
        assert_eq!(k.dat[99], 1);
        assert_eq!(k.dat[100], 2);
        assert_eq!(k.dat[299], 2);
        assert_eq!(k.dat[512], 3);
        assert_eq!(k.asm.matches("fdb $").count(), 2); // two segments (the terminator is `fdb 0`)
    }

    #[test]
    fn guards_fire() {
        let lo = (0x7600, 0x77c0);
        // spill into the loader: block ends at $7600 exactly -> fine ...
        assert!(pack(&[(0x6000, vec![0; 0x1600])], 0x6000, lo, 0xFF00).is_ok());
        // ... one byte longer pads to $7700 -> into the loader
        assert!(pack(&[(0x6000, vec![0; 0x1601])], 0x6000, lo, 0xFF00).is_err());
        // padded end reaching the I/O page
        assert!(pack(&[(0xFE80, vec![0; 0x41])], 0x6000, lo, 0xFF00).is_err());
        // overlapping blocks
        assert!(pack(&[(0x2000, vec![0; 0x200]), (0x2100, vec![0; 4])], 0x2000, lo, 0xFF00).is_err());
    }
}
