#!/usr/bin/env bash
# Producer for target/dizzy_frames_{bodyA,bodyB,tail}.asm (T0107 split, NOTES.md "T0107 DONE").
#
# Input: the RAW output of `spritedata dizzy-pack-all` (target/dizzy_frames_all.asm).
#   bodyA = header + frames 0-7            -> r8000 staging window
#   bodyB = header + frames 8-35 + trailer -> r9800 staging window
#   tail  = preamble (incl. `org $5800`) + frames 36-38 + the three lookup tables
#           -> resident, in the $5800 inter-buffer gap
# bodyB_trailer.txt and tail_preamble.txt are the port-authored comment blocks that the
# hand-edited dizzy_frames_all.asm carried (the memory-gap rationale and the `org $5800`);
# they are the only non-generated bytes. Output is byte-identical to the pre-bootstrap files.
#
# Usage: tools/dizzy_split/split.sh [ALL_ASM [OUT_DIR]]   (defaults: target/dizzy_frames_all.asm, target)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$HERE/../.."
# explicit arguments are relative to the caller's cwd; the defaults to the port root
IN=$(realpath -m "${1:-$ROOT/target/dizzy_frames_all.asm}")
OUT=$(realpath -m "${2:-$ROOT/target}")
[ -f "$IN" ] || { echo "split.sh: $IN not found (run spritedata dizzy-pack-all first)" >&2; exit 1; }
n=$(grep -c '^dizzy_frame[0-9][0-9]_\(mask\|sprite\)' "$IN")
[ "$n" = 78 ] || { echo "split.sh: expected 78 frame lines in $IN, found $n (is it the raw dizzy-pack-all output?)" >&2; exit 1; }
if grep -q '^ *org ' "$IN"; then
    echo "split.sh: $IN already contains an org directive (hand-edited, not raw dizzy-pack-all output)" >&2; exit 1
fi
hdr() { awk '/^dizzy_frame[0-9][0-9]_(mask|sprite)/ {exit} {print}' "$IN"; }
frames() { # frames LO HI
    awk -v lo="$1" -v hi="$2" '
        match($0, /^dizzy_frame[0-9][0-9]_(mask|sprite)/) { k = substr($0, 12, 2) + 0; if (k >= lo && k <= hi) print }' "$IN"
}
rest() { awk 'seen && !/^dizzy_frame[0-9][0-9]_(mask|sprite)/ {print} /^dizzy_frame[0-9][0-9]_(mask|sprite)/ {seen=1}' "$IN"; }
mkdir -p "$OUT"
{ hdr; frames 0 7; } > "$OUT/dizzy_frames_bodyA.asm"
{ hdr; frames 8 35; cat "$HERE/bodyB_trailer.txt"; } > "$OUT/dizzy_frames_bodyB.asm"
{ cat "$HERE/tail_preamble.txt"; frames 36 38; rest; } > "$OUT/dizzy_frames_tail.asm"
echo "split $IN -> $OUT/dizzy_frames_{bodyA,bodyB,tail}.asm"
