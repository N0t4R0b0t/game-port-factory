#!/usr/bin/env bash
# T0241 -- builds target/dizzy.dsk: the RS-DOS floppy build.
#
#   LOADM"DIZZY":EXEC          (Disk BASIC reads DIZZY.BIN = target/floppy_stage1.asm, which streams
#                               DIZZY.DAT = the game image off the disk with a private driver)
#
# FLOPPY=1 on top of TAPE_ROOMS=1 -- its OWN complete tools/stage_pack.sh run, artifacts suffixed
# _floppy, nothing shared with the -run (room36.bin) or tape (room36_tape.bin / room36.cas) builds.
# This script never touches those two builds' outputs.  See NOTES.md T0241 for the design.
#
# Usage: tools/floppy_pack.sh [--no-stage]     (--no-stage reuses target/room36_floppy.bin/.map)
set -euo pipefail
cd "$(dirname "$0")/.."

DSK=tools/dskwriter/target/release/dskwriter
FPK=tools/dskwriter/target/release/floppypack
[ -x "$DSK" ] && [ -x "$FPK" ] || cargo build --release --manifest-path tools/dskwriter/Cargo.toml

if [ "${1:-}" != "--no-stage" ]; then
    echo "== stage_pack (FLOPPY=1, fully independent; run twice so the generated artifacts settle) =="
    FLOPPY=1 tools/stage_pack.sh > ${GPF_TMP:-/tmp}/floppy_stage_pack1.log 2>&1 || { tail -20 ${GPF_TMP:-/tmp}/floppy_stage_pack1.log; exit 1; }
    FLOPPY=1 tools/stage_pack.sh > ${GPF_TMP:-/tmp}/floppy_stage_pack2.log 2>&1 || { tail -20 ${GPF_TMP:-/tmp}/floppy_stage_pack2.log; exit 1; }
    if grep -q "TITLE_RESIDENT_LEN changed" ${GPF_TMP:-/tmp}/floppy_stage_pack2.log; then
        echo "floppy_pack.sh: TITLE_RESIDENT_LEN still moving after two runs" >&2; exit 1
    fi
fi
BIN=target/room36_floppy.bin
MAP=target/room36_floppy.map
OUT=target/floppy
mkdir -p "$OUT"

# --- the loader: assemble once with a dummy range to measure it, then place it -------------------
LAYOUT=target/floppy_layout.asm
sym() { grep "^Symbol: $1 " "$MAP" | awk '{print $NF}'; }
lw() { # assemble loader at ORG, segs file in $OUT; RES_FD_*: the resident driver's state bytes (drive hand-over)
    lwasm --decb -DFDX_WRITE=0 -DFDX_SAVEVEC=0 -DLOADER_ORG=$1 -DLOADER_STACK=$2 \
          -DRES_FD_MOT=$((16#$(sym fd_mot))) -DRES_FD_HD=$((16#$(sym fd_hd))) \
          -I"$OUT" -Itarget -o "$OUT/DIZZY.BIN" --map="$OUT/loader.map" target/floppy_stage1.asm
}
$FPK --decb $BIN --dat "$OUT/DIZZY.DAT" --segs "$OUT/floppy_segs.asm" --loader-org 0x7600 --loader-end 0x7800 > /dev/null \
    || { echo "(first floppypack with the nominal window failed; details below)"; $FPK --decb $BIN --dat "$OUT/DIZZY.DAT" --segs "$OUT/floppy_segs.asm" --loader-org 0x7600 --loader-end 0x7800; exit 1; }
lw $((0x7600)) $((0x7800))
LOADER_END=$((16#$(grep '^Symbol: LOADER_END ' "$OUT/loader.map" | awk '{print $NF}')))
LOADER_LEN=$((LOADER_END - 0x7600))
STACK_NEED=40
LOADER_WINDOW=512
if [ $((LOADER_LEN + STACK_NEED)) -gt $LOADER_WINDOW ]; then
    echo "floppy_pack.sh: loader is $LOADER_LEN bytes (+$STACK_NEED stack) but the framebuffer-B window [\$7600,\$7800) is $LOADER_WINDOW" >&2
    exit 1
fi
# the real run of the packer, with the loader's true extent as the no-spill guard
$FPK --decb $BIN --dat "$OUT/DIZZY.DAT" --segs "$OUT/floppy_segs.asm" --loader-org 0x7600 --loader-end $(printf '0x%x' $((0x7800)))
lw $((0x7600)) $((0x7800))
echo "   loader DIZZY.BIN: $LOADER_LEN bytes at \$7600..\$$(printf '%04x' $LOADER_END) (window $LOADER_WINDOW, stack room $((LOADER_WINDOW - LOADER_LEN)) bytes)"

# --- the overlays ---------------------------------------------------------------------------------------
# resident symbol table for the standalone overlay assemblies: EVERY symbol of the final map as an equ,
# except the labels the overlay source defines itself.
lwasm --format=raw -o "$OUT/title_ovl.bin" target/title_resident_lz_floppy.asm
python3 - "$MAP" "$OUT" <<'PY'
import re, sys
mp, out = sys.argv[1], sys.argv[2]
src = open('target/tape_heart_code.asm').read()
src = re.sub(r'^\s+ifndef HEART_OVL\n.*?^\s+endif\n', '', src, flags=re.S | re.M)   # resident under FLOPPY (hd_random, hd_dir, hd_seed)
src = re.sub(r'^\s+ifndef HEART_RES\n', '        if 1\n', src, flags=re.M)
own = set(m.group(1) for m in re.finditer(r'^([A-Za-z_]\w*)', src, re.M))
own -= {'ifndef', 'endif', 'ifgt', 'include', 'org', 'fcb', 'fdb', 'rts', 'else'}
own |= {'HEART_RES', 'HEART_OVL'}      # build-mode switches of the overlay source, never resident equs here
lines = ['; Generated by tools/floppy_pack.sh from the final room36_floppy.map -- do not edit.']
n = 0
for l in open(mp):
    m = re.match(r'^Symbol: (\S+) \(.*?\) = ([0-9A-Fa-f]+)$', l.strip())
    if m and m.group(1) not in own and re.match(r'^[A-Za-z_]\w*$', m.group(1)):
        lines.append(f'{m.group(1)} equ ${m.group(2)}'); n += 1
open(f'{out}/resident_syms.asm', 'w').write('\n'.join(lines) + '\n')
print(f'   resident symbol table for the overlays: {n} symbols')
PY
TW_OFF=$((16#$(grep '^Symbol: TW_OFF ' "$MAP" | awk '{print $NF}')))
BUFA_HEX=$(grep '^Symbol: BUFA ' "$MAP" | awk '{print $NF}'); BUFB_HEX=$(grep '^Symbol: BUFB ' "$MAP" | awk '{print $NF}')
for V in A B; do
    if [ $V = A ]; then BASE=$((16#$BUFA_HEX + TW_OFF)); else BASE=$((16#$BUFB_HEX + TW_OFF)); fi
    printf '        include "resident_syms.asm"\n        org %d\n        include "tape_heart_code.asm"\n' $BASE > "$OUT/heart_$V.asm"
    lwasm --format=raw -DHEART_OVL=1 -I"$OUT" -Itarget -o "$OUT/heart_$V.bin" --map="$OUT/heart_$V.map" "$OUT/heart_$V.asm"
done
# T0242: the quick-save overlay (OVL_SAVE_A/B).  State set: target/floppy_state.txt checked against every store in the listing.
python3 tools/state_set.py --json "$OUT/state_static.json" > /dev/null
python3 tools/floppy_state_check.py --no-dyn || { echo "floppy_pack.sh: the state manifest is incomplete (tools/floppy_state_check.py)" >&2; exit 1; }
cp "$OUT/state_ranges.asm" "$OUT/state_ranges_used.asm"
BID=$(python3 -c "import zlib;print(zlib.crc32(open('$BIN','rb').read()))")
for V in A B; do
    if [ $V = A ]; then BASE=$((16#$BUFA_HEX + TW_OFF)); else BASE=$((16#$BUFB_HEX + TW_OFF)); fi
    printf '        include "resident_syms.asm"\nBASE equ %d\n        org BASE\n        include "floppy_save.asm"\n' $BASE > "$OUT/save_$V.asm"
    lwasm --format=raw -DBUILD_HI=$((BID >> 16)) -DBUILD_LO=$((BID & 65535)) -I"$OUT" -Itarget -o "$OUT/save_$V.bin" --map="$OUT/save_$V.map" "$OUT/save_$V.asm"
done
echo "   quick-save overlays: $(stat -c%s "$OUT/save_A.bin") bytes each, build ID $(printf '%08x' $BID)"
echo "   heart demo overlays: A (hidden buffer A at \$$(printf '%04x' $((16#$BUFA_HEX + TW_OFF)))) $(stat -c%s "$OUT/heart_A.bin") bytes, B $(stat -c%s "$OUT/heart_B.bin") bytes"

# --- DIZZY.OVL: the slots ---------------------------------------------------------------------------------
python3 - "$OUT" <<'PY'
import re, sys, os
out = sys.argv[1]
lay = {m.group(1): int(m.group(2)) for m in re.finditer(r'^(\w+)\s+equ\s+(\d+)', open('target/floppy_layout.asm').read(), re.M)}
slots = [('TITLE', f'{out}/title_ovl.bin'), ('HEART_A', f'{out}/heart_A.bin'), ('HEART_B', f'{out}/heart_B.bin'), ('SAVE_A', f'{out}/save_A.bin'), ('SAVE_B', f'{out}/save_B.bin'), ('SPARE', None)]
img = bytearray()
idx = 0
for name, path in slots:
    cap = lay[f'OVL_{name}_CAP']
    trk, sec = lay[f'OVL_{name}_TRK'], lay[f'OVL_{name}_SEC']
    assert (trk, sec) == (idx // 18, idx % 18 + 1), f'OVL_{name} track/sector {trk}/{sec} does not match slot index {idx} (floppy_layout.asm)'
    data = open(path, 'rb').read() if path and os.path.exists(path) else b''
    assert len(data) <= cap * 256, f'overlay {name}: {len(data)} bytes > {cap} sectors'
    img += data.ljust(cap * 256, b'\0')
    idx += cap
assert idx == lay['OVL_GRANS'] * 9, f'slots total {idx} sectors, DIZZY.OVL is {lay["OVL_GRANS"]*9}'
open(f'{out}/DIZZY.OVL', 'wb').write(img)
print(f'   DIZZY.OVL: {len(img)} bytes; title {os.path.getsize(out + "/title_ovl.bin")} B, heart A/B {os.path.getsize(out + "/heart_A.bin")} B each')
PY

# --- the disk -----------------------------------------------------------------------------------------
$DSK build target/dizzy.dsk \
    --type 1 --at $(grep '^OVL_GRAN ' $LAYOUT | awk '{print $3}') --file DIZZY.OVL "$OUT/DIZZY.OVL" \
    --type 1 --at $(grep '^SAV_GRAN '  $LAYOUT | awk '{print $3}') --reserve $(( $(grep '^SAV_GRANS ' $LAYOUT | awk '{print $3}') * 2304 )) --file DIZZY.SAV - \
    --type 1 --at $(grep '^DAT_GRAN '  $LAYOUT | awk '{print $3}') --file DIZZY.DAT "$OUT/DIZZY.DAT" \
    --type 2 --file DIZZY.BIN "$OUT/DIZZY.BIN"
# the constants in floppy_layout.asm must be where the disk put things
python3 - <<'PY'
import re, subprocess
lay = {m.group(1): int(m.group(2)) for m in re.finditer(r'^(\w+)\s+equ\s+(\d+)', open('target/floppy_layout.asm').read(), re.M)}
def loc(n):
    t, s, secs, by = map(int, subprocess.check_output(['tools/dskwriter/target/release/dskwriter', 'locate', 'target/dizzy.dsk', n]).split())
    return t, s, secs
assert loc('DIZZY.OVL')[:2] == (0, 1), loc('DIZZY.OVL')
assert loc('DIZZY.SAV') == (lay['SAV_TRK'], lay['SAV_SEC'], lay['SAV_SECS']), loc('DIZZY.SAV')
assert loc('DIZZY.DAT')[:2] == (lay['DAT_TRK'], lay['DAT_SEC']), loc('DIZZY.DAT')
print('   layout check: DIZZY.OVL (0,1)  DIZZY.SAV', loc('DIZZY.SAV'), ' DIZZY.DAT', loc('DIZZY.DAT')[:2], ' -- match floppy_layout.asm')
PY
$DSK ls target/dizzy.dsk
echo "   target/dizzy.dsk: $(stat -c%s target/dizzy.dsk) bytes"
echo "== RAM audit (tools/ramaudit.py --floppy) =="
python3 tools/ramaudit.py --floppy > target/floppy/ramaudit.txt && grep -E "persistent FREE|^    [0-9A-F]{4}-" target/floppy/ramaudit.txt | head -12
echo "   (tape build for comparison: $(python3 tools/ramaudit.py | grep 'persistent FREE' | sed 's/.*: //') persistent free bytes; full tables: target/floppy/ramaudit.txt)"
